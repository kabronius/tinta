#!/usr/bin/env python3
"""Generate colors/defaults.xml and xml/Variables_Colors.xml from the M3 roles of the colour service."""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / "script.tinta.colors" / "resources" / "lib"))
import palette  # noqa: E402

skin = root / "skin.tinta"
scheme = palette.default_scheme()
scheme["Seed"] = palette.DEFAULT_SEED


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


colors = ['<?xml version="1.0" encoding="UTF-8"?>', "<!-- Generated by tools/gen_colors.py -->", "<colors>",
          '\t<color name="transparent">00000000</color>', '\t<color name="black">FF000000</color>',
          '\t<color name="white">FFFFFFFF</color>', '\t<color name="scrim">99000000</color>',
          '\t<color name="scrim_strong">CC000000</color>']
var = ['<?xml version="1.0" encoding="UTF-8"?>',
       "<!-- Generated by tools/gen_colors.py: dynamic M3 roles (script.tinta.colors) with a static fallback -->",
       "<includes>"]
for role, rgb in scheme.items():
    n = snake(role)
    colors.append(f'\t<color name="base_{n}">{palette.to_argb(rgb)}</color>')
    var.append(f'\t<variable name="c_{n}">')
    var.append(f'\t\t<value condition="!String.IsEmpty(Window(Home).Property(Tinta.{role}))">$INFO[Window(Home).Property(Tinta.{role})]</value>')
    var.append(f'\t\t<value>{palette.to_argb(rgb)}</value>')
    var.append("\t</variable>")
colors.append("</colors>")
var.append("</includes>")
(skin / "colors").mkdir(exist_ok=True)
(skin / "colors" / "defaults.xml").write_text("\n".join(colors) + "\n")
(skin / "xml" / "Variables_Colors.xml").write_text("\n".join(var) + "\n")
print(", ".join("c_" + snake(r) for r in scheme))
