#!/usr/bin/env python3
"""Generate the Movies (1110) and TV shows (1111) pages and the slot buttons of Settings › Appearance.

Each page has ROWS rows; row N shows Skin.String(tinta.<page>.N.path), assigned with the "Use in Tinta…"
context entry of script.tinta.colors. An empty row is hidden.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
XML = ROOT / "skin.tinta" / "xml"
ROWS = 4
PAGES = (("Movies", 1110, "movies", 342), ("Shows", 1111, "shows", 20343))


def page(name, wid, key, title):
    rows = []
    for n in range(1, ROWS + 1):
        slot = f"tinta.{key}.{n}"
        rows.append(f'''			<include content="PosterRow">
				<param name="id">{wid * 10 + n}</param>
				<param name="title">$INFO[Skin.String({slot}.label)]</param>
				<param name="path">$INFO[Skin.String({slot}.path)]</param>
				<param name="visible">!String.IsEmpty(Skin.String({slot}.path))</param>
			</include>''')
    empty = " + ".join(f"String.IsEmpty(Skin.String(tinta.{key}.{n}.path))" for n in range(1, ROWS + 1))
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/gen_pages.py: {name} page, rows from slots tinta.{key}.1..{ROWS}. -->
<window type="window" id="{wid}">
	<defaultcontrol always="true">{wid}0</defaultcontrol>
	<include>AnimWindow</include>
	<controls>
		<include>Background</include>
		<include>NavRail</include>
		<include content="TopAppBar">
			<param name="title">$LOCALIZE[{title}]</param>
			<param name="back">false</param>
			<param name="titleleft">11</param>
		</include>
		<control type="grouplist" id="{wid}0">
			<left>231</left><top>176</top><right>55</right><bottom>0</bottom>
			<orientation>vertical</orientation>
			<itemgap>33</itemgap>
			<scrolltime tween="cubic" easing="out">300</scrolltime>
			<onleft>9101</onleft>
{chr(10).join(rows)}
		</control>
		<!-- no row assigned -->
		<control type="group">
			<left>231</left><top>220</top><width>1400</width><height>410</height>
			<visible>{empty}</visible>
			<include content="Shape">
				<param name="r">77</param>
				<param name="color">$VAR[c_surface_container]</param>
			</include>
			<include content="Icon">
				<param name="left">66</param><param name="top">66</param>
				<param name="width">121</param><param name="height">121</param>
				<param name="font">icon_xl_fill</param>
				<param name="icon">{{ic:playlist_play}}</param>
				<param name="color">$VAR[c_primary]</param>
			</include>
			<control type="textbox">
				<left>66</left><top>220</top><right>66</right><height>160</height>
				<label>$LOCALIZE[31049]</label>
				<font>body_l</font>
				<textcolor>$VAR[c_on_surface_variant]</textcolor>
			</control>
		</control>
	</controls>
</window>
'''


def settings():
    out = []

    def section(label):
        out.append(f'''			<control type="label">
				<width>1700</width><height>110</height>
				<label>{label}</label>
				<font>title_s</font>
				<textcolor>$VAR[c_primary]</textcolor>
				<aligny>bottom</aligny>
				<textoffsetx>44</textoffsetx>
			</control>''')

    def button(bid, label, slot):
        out.append(f'''			<control type="button" id="{bid}">
				<width>1700</width><height>154</height>
				<label>{label}</label>
				<label2>$VAR[SlotLabel_{slot.replace(".", "_")}]</label2>
				<include>SettingRowStyle</include>
				<onclick>RunScript(script.tinta.colors,slot,{slot})</onclick>
			</control>''')

    variables = []
    bid = 710
    for _, _, key, title in PAGES:
        section(f"$LOCALIZE[{title}]")
        for n in range(1, ROWS + 1):
            bid += 1
            button(bid, f"$LOCALIZE[31048] {n}", f"{key}.{n}")
            variables.append(f"{key}.{n}")
    section("$LOCALIZE[31039]")
    button(731, "$LOCALIZE[31038]", "live")
    button(732, "$LOCALIZE[137]", "search")
    variables += ["live", "search"]
    vars_xml = "\n".join(f'''	<variable name="SlotLabel_{v.replace(".", "_")}">
		<value condition="!String.IsEmpty(Skin.String(tinta.{v}.label))">$INFO[Skin.String(tinta.{v}.label)]</value>
		<value>$LOCALIZE[31045]</value>
	</variable>''' for v in variables)
    return "\n".join(out), vars_xml


def main():
    for name, wid, key, title in PAGES:
        (XML / f"Custom_{wid}_{name}.xml").write_text(page(name, wid, key, title))
    buttons, vars_xml = settings()
    (XML / "Includes_Slots.xml").write_text(f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/gen_pages.py: content slots in the skin settings. -->
<includes>
	<include name="SlotSettings">
{buttons}
	</include>
{vars_xml}
</includes>
''')
    print("pages and slots generated")


if __name__ == "__main__":
    main()
